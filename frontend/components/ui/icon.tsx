/**
 * Weight/style suffixes that are a SET's vocabulary, not part of the concept:
 * Phosphor's `-duotone`, Solar's `-bold-duotone`, Material's `-outline`. A name
 * carrying one resolves to the same glyph as the name without it.
 */
const WEIGHT_SUFFIX =
  /-(?:outline|line|fill|filled|duotone|bold|solid|thin|light|regular|rounded|round|sharp|two-tone|variant)+$/;

/**
 * Resolve a stored icon name to a component.
 *
 * Tries, in order: the name verbatim; lowercased; with the set prefix dropped
 * (`mdi:magnify` -> `magnify`); and with trailing weight suffixes stripped
 * (`ph:gear-duotone` -> `gear`). Returns `undefined` when nothing matches — the
 * CALLER picks the fallback, because a menu wants a different stand-in than a
 * KPI tile does.
 *
 * Unlike the Iconify component this replaced, an unknown name cannot be fetched
 * into existence at runtime; it resolves to `undefined` and the caller's
 * fallback draws. That is the intended trade — `pnpm gate:icons` turns an
 * unresolvable name into a build failure rather than a blank space in prod.
 */
export function resolveIcon(name?: string | null): IconComponent | undefined {
  if (!name) return undefined;
  const raw = name.trim();
  if (!raw) return undefined;

  const direct = ICONS[raw];
  if (direct) return direct;

  const lower = raw.toLowerCase();
  if (ICONS[lower]) return ICONS[lower];

  const colon = lower.indexOf(":");
  const bare = colon >= 0 ? lower.slice(colon + 1) : lower;
  if (ICONS[bare]) return ICONS[bare];

  const stripped = bare.replace(WEIGHT_SUFFIX, "");
  return stripped !== bare ? ICONS[stripped] : undefined;
}

/** @returns true when `name` draws something. Used by the build gate. */
export function isKnownIcon(name?: string | null): boolean {
  return resolveIcon(name) !== undefined;
}

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "ref"> {
  /** A stored icon name in any of the supported shapes. */
  icon?: string | null;
  size?: number | string;
  /** Drawn when `icon` does not resolve. Omit to render nothing. */
  fallback?: IconComponent;
}

/**
 * Drop-in replacement for `@iconify/react`'s `<Icon icon="…">` at the call
 * sites that resolve a name at RUNTIME — nav menus, payment rails, KPI configs
 * — where the name comes from a table and cannot become a static import.
 *
 * Call sites that know their glyph at author time should import it straight
 * from `lucide-react` instead: that tree-shakes to the one icon, while this
 * pulls the whole table.
 */
export function Icon({ icon, fallback, ...props }: IconProps) {
  const Resolved = resolveIcon(icon) ?? fallback;
  if (!Resolved) return null;
  return <Resolved {...props} />;
}

/**
 * The names a PICKER may offer — one per glyph, all guaranteed to draw.
 *
 * DERIVED FROM THE REGISTRY, NOT HAND-LISTED. The map above carries roughly
 * 1,300 keys for ~350 components: `lucide:wallet`, `mdi:wallet-outline`,
 * `wallet` and `Wallet` are four names for one picture. Offering all of them
 * would be a picker in which most choices are indistinguishable, and offering a
 * hand-kept subset would be a second list to keep in step with this one — the
 * exact failure `home-icons.test.ts` exists to catch elsewhere.
 *
 * The PascalCase keys are the canonical shape: `resolveIcon` matches them
 * verbatim, they are one-per-component by construction, and an object cannot
 * hold a duplicate. So an icon that exists here is offerable, and an icon
 * dropped from the map disappears from every picker on the next build rather
 * than becoming a stored name that renders nothing.
 */
export const ICON_NAMES: readonly string[] = Object.freeze(
  Object.keys(ICONS)
    .filter((key) => /^[A-Z][A-Za-z0-9]*$/.test(key))
    .sort((a, b) => a.localeCompare(b))
);
