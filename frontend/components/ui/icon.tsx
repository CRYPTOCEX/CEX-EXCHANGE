/**
 * The one place an icon NAME becomes an icon COMPONENT.
 * ============================================================================
 *
 * WHY THIS EXISTS. 141 files rendered `<Icon icon="mdi:foo">` from
 * `@iconify/react`, which resolves a glyph by FETCHING its set from
 * `api.iconify.design` at runtime. Three consequences, all of them bugs:
 *
 *   1. An operator behind a firewall got pages with no icons at all — and
 *      could not fix it from their own egress rules, because the call is made
 *      by every VISITOR's browser, not by their server.
 *   2. Every one of their customers' browsers contacted a third party the
 *      operator never chose.
 *   3. It was the slow path anyway. Nothing could even START loading until the
 *      bundle had parsed and hydrated; only then a cold DNS + TLS handshake to
 *      an origin that cannot share our HTTP/2 connection, then a re-render. So
 *      every glyph landed after LCP, and `<Button loading>` shipped a spinner
 *      that itself waited on the network to appear.
 *
 * Three files had already reasoned this out in isolation and fixed only
 * themselves — `symbol-explorer.tsx` ("costs an extra round trip to an
 * external CDN"), `kpi/icon.tsx` (its own 198-entry alias table), and
 * `rail-icon.tsx` ("icon sets this app no longer bundles"). This module is
 * those three tables merged, so the next renderer that needs a name resolved
 * does not start a fourth.
 *
 * WHAT IT COSTS. 328 lucide glyphs, ~194KB raw / ~25KB gzip, against the 51KB
 * `@iconify/react` runtime it replaces. The nav chrome resolves names from the
 * menu tables on EVERY page, so this map is in the shared chunk regardless —
 * which is why the other consumers import it rather than keeping private
 * copies. In exchange the glyph is inline SVG in the server-rendered HTML: no
 * request, no pop-in, no layout shift, and it works offline.
 *
 * ADDING A NAME. Put it in `ICONS` below. `pnpm gate:icons` fails the build on
 * any `icon:`/`icon=` string in the tree that this table cannot resolve, which
 * is what stops the drift that produced the original 141-file split.
 */

